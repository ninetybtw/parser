BY_KEY = {p.key: p for p in PROFILES}
GENERIC = BY_KEY["generic"]


def get(key: str) -> NicheProfile:
    return BY_KEY.get(key, GENERIC)


def score(profile: NicheProfile, text: str) -> int:
    low = text.lower()
    return sum(1 for kw in profile.keywords if kw in low)


def resolve(query: str) -> NicheProfile:
    """Профиль по запросу пользователя («ремонт техники» → repair)."""
    low = query.lower()
    for p in PROFILES:
        if low == p.title.lower() or low == p.key:
            return p
    return classify(query)


def classify(text: str, hint: NicheProfile | None = None) -> NicheProfile:
    """Профиль по тексту лида. Подсказка (ниша поиска) выигрывает при равенстве и
    используется, если текст ни на что не похож — лид ведь нашёлся по этой нише."""
    best, best_score = None, 0
    for p in PROFILES:
        s = score(p, text)
        if hint is not None and p.key == hint.key:
            s += 1 if s else 0
        if s > best_score:
            best, best_score = p, s
    if best is not None:
        return best
    return hint or GENERIC
